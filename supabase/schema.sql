-- 1. Crear la tabla de movimientos financieros
CREATE TABLE IF NOT EXISTS public.transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK (type IN ('ingreso', 'gasto')),
  description TEXT NOT NULL,
  amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
  category TEXT NOT NULL DEFAULT 'General',
  date TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Habilitar Row Level Security (RLS)
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;

-- 3. Política de acceso general (Sin autenticación por ahora)
-- Permite leer, insertar y eliminar movimientos desde la app usando la clave pública (anon key).
CREATE POLICY "Permitir acceso público a transactions"
  ON public.transactions
  FOR ALL
  USING (true)
  WITH CHECK (true);

